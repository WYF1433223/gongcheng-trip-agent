def city_json(key: str) -> dict:
    """把种子行展开成 cities/<key>.json 的结构。"""
    name, rows = SEED[key]
    pois = []
    far_ids = []
    for idx, (pname, lat, lng, oh, ch, dur, price, rating, tag, outdoor, closed, far) in enumerate(rows):
        pid = f"{key}_{idx + 1:02d}"
        pois.append({
            "id": pid,
            "name": pname,
            "district": name,
            "lat": lat,
            "lng": lng,
            "open_min": int(round(oh * 60)),
            "close_min": int(round(ch * 60)),
            "duration": dur,
            "price": price,
            "rating": rating,
            "tags": [tag],
            "outdoor": bool(outdoor),
            "closed_weekday": closed,
        })
        if far:
            far_ids.append(pid)
    lat0 = sum(p["lat"] for p in pois) / len(pois)
    lng0 = sum(p["lng"] for p in pois) / len(pois)
    return {
        "name": name,
        "center": [round(lat0, 4), round(lng0, 4)],
        "pois": pois,
        "hotels": {
            "市中心": [round(lat0, 4), round(lng0, 4)],
            "老城区": [round(lat0 + 0.01, 4), round(lng0 - 0.01, 4)],
            "近郊": [round(lat0 + 0.04, 4), round(lng0 + 0.03, 4)],
        },
        "weather": [
            {"day": "第1天", "text": "晴", "low": 14, "high": 24, "rain": 5},
            {"day": "第2天", "text": "多云", "low": 13, "high": 22, "rain": 15},
            {"day": "第3天", "text": "小雨", "low": 12, "high": 19, "rain": 70},
            {"day": "第4天", "text": "阴", "low": 12, "high": 20, "rain": 25},
            {"day": "第5天", "text": "晴", "low": 13, "high": 23, "rain": 5},
        ],
        "far_ids": far_ids,
        "far_minutes": 60,
        "far_both_minutes": 90,
    }

